-- V1: Initialize RANKFORGE Core Schema (PostgreSQL & H2 Compatible)

CREATE TABLE IF NOT EXISTS players (
    id INT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    score INT NOT NULL DEFAULT 0,
    level INT NOT NULL DEFAULT 1,
    team VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS matchmaking_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id INT NOT NULL UNIQUE,
    slot_index INT NOT NULL,
    enqueued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_queue_player FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_type VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    winning_side VARCHAR(20),
    score_award INT NOT NULL DEFAULT 10,
    summary VARCHAR(255),
    played_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    undone_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS match_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    player_id INT NOT NULL,
    player_name VARCHAR(100) NOT NULL,
    player_team VARCHAR(100),
    player_level INT NOT NULL DEFAULT 1,
    side VARCHAR(10) NOT NULL,
    dice_roll INT NOT NULL,
    is_winner BOOLEAN NOT NULL DEFAULT FALSE,
    score_delta INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_part_match FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE,
    CONSTRAINT fk_part_player FOREIGN KEY (player_id) REFERENCES players(id)
);

CREATE TABLE IF NOT EXISTS match_tie_rerolls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    round_number INT NOT NULL,
    side_alpha_roll INT NOT NULL,
    side_omega_roll INT NOT NULL,
    CONSTRAINT fk_reroll_match FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_queue_slot ON matchmaking_queue(slot_index);
CREATE INDEX IF NOT EXISTS idx_matches_played_at ON matches(played_at DESC);
CREATE INDEX IF NOT EXISTS idx_matches_status ON matches(status);
CREATE INDEX IF NOT EXISTS idx_part_match_id ON match_participants(match_id);
CREATE INDEX IF NOT EXISTS idx_part_player_id ON match_participants(player_id);
